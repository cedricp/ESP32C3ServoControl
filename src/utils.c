const char *reset_reason_to_str(uint8_t reason)
{
    switch (reason)
    {
    case ESP_RST_POWERON:
        return "POWERON";
    case ESP_RST_EXT:
        return "EXTERNAL_PIN";
    case ESP_RST_SW:
        return "SOFTWARE_RESET";
    case ESP_RST_PANIC:
        return "EXCEPTION_PANIC";
    case ESP_RST_INT_WDT:
        return "INTERRUPT_WATCHDOG";
    case ESP_RST_TASK_WDT:
        return "TASK_WATCHDOG";
    case ESP_RST_WDT:
        return "OTHER_WATCHDOG";
    case ESP_RST_DEEPSLEEP:
        return "DEEP_SLEEP_EXIT";
    case ESP_RST_BROWNOUT:
        return "BROWNOUT_RESET";
    case ESP_RST_SDIO:
        return "SDIO_RESET";
    default:
        return "UNKNOWN";
    }
}

static const char *TAG_I2C = "I2C_RECOVERY";

void i2c_bus_recovery(int gpio_sda, int gpio_scl)
{
    // 1. Configurer SCL et SDA en Open-Drain avec pull-up
    gpio_config_t io_conf = {
        .pin_bit_mask = (1ULL << gpio_scl) | (1ULL << gpio_sda),
        .mode         = GPIO_MODE_INPUT_OUTPUT_OD,
        .pull_up_en   = GPIO_PULLUP_ENABLE,
        .pull_down_en = GPIO_PULLDOWN_DISABLE,
        .intr_type    = GPIO_INTR_DISABLE,
    };
    gpio_config(&io_conf);

    // Relâcher les lignes
    gpio_set_level(gpio_scl, 1);
    gpio_set_level(gpio_sda, 1);
    esp_rom_delay_us(10);

    // 2. Générer 9 impulsions d'horloge sur SCL pour forcer le MPU6500 à relâcher SDA
    for (int i = 0; i < 9; i++)
    {
        gpio_set_level(gpio_scl, 0);
        esp_rom_delay_us(5);
        gpio_set_level(gpio_scl, 1);
        esp_rom_delay_us(5);

        // Si SDA est libéré (remonté à 1), le MPU6500 est sorti de son cycle
        if (gpio_get_level(gpio_sda) == 1)
        {
            break;
        }
    }

    // 3. Émettre un STOP manuel : SDA passe de 0 à 1 pendant que SCL est à 1
    gpio_set_level(gpio_scl, 0);
    esp_rom_delay_us(5);
    gpio_set_level(gpio_sda, 0);
    esp_rom_delay_us(5);
    gpio_set_level(gpio_scl, 1);
    esp_rom_delay_us(5);
    gpio_set_level(gpio_sda, 1); // Front montant de SDA avec SCL à 1 = STOP
    esp_rom_delay_us(10);

    if (gpio_get_level(gpio_sda) == 0)
    {
        ESP_LOGE(TAG_I2C, "SDA still locked after recovery !");
    }
    else
    {
        ESP_LOGI(TAG_I2C, "I2C bus unlocked successfully.");
    }
}

void check_i2c(int gpio_sda, int gpio_scl)
{
    gpio_config_t io_conf = {
        .pin_bit_mask   = (1ULL << gpio_sda),
        .mode           = GPIO_MODE_INPUT,          // simple lecture, pas encore open-drain
        .pull_up_en     = GPIO_PULLUP_ENABLE, // au cas où le pull-up externe serait faible/absent
        .pull_down_en   = GPIO_PULLDOWN_DISABLE,
        .intr_type      = GPIO_INTR_DISABLE,
    };
    gpio_config(&io_conf);

    esp_rom_delay_us(10); // laisser le pull-up stabiliser la ligne

    int sda_level = gpio_get_level(gpio_sda);
    if (sda_level == 0)
    {
        ESP_LOGI("I2C", "I2C Bus recovery try");
        i2c_bus_recovery(gpio_sda, gpio_scl);
    }
}

esp_err_t nvs_save_struct(const char *key, const void *data, size_t size)
{
    nvs_handle_t handle = 0;
    esp_err_t err = nvs_open(NVS_NAMESPACE, NVS_READWRITE, &handle);
    if (err != ESP_OK)
    {
        ESP_LOGE("NVS", "Error opening NVS namespace for save '%s' [%s]", NVS_NAMESPACE, esp_err_to_name(err));
        return err;
    }

    // Écriture du bloc mémoire brut (BLOB)
    err = nvs_set_blob(handle, key, data, size);
    if (err == ESP_OK)
    {
        err = nvs_commit(handle); // Validation de l'écriture en Flash
    }
    else
    {
        ESP_LOGE("NVS", "Failed to write key %s [%s]", key, esp_err_to_name(err));
    }

    nvs_close(handle);
    return err;
}

esp_err_t nvs_load_struct(const char *key, void *data, size_t size)
{
    nvs_handle_t handle = 0;
    esp_err_t err = nvs_open(NVS_NAMESPACE, NVS_READONLY, &handle);
    if (err != ESP_OK)
    {
        ESP_LOGE("NVS", "Error opening NVS namespace for load '%s' [%s]", NVS_NAMESPACE, esp_err_to_name(err));
        return err;
    }

    size_t required_size = size;
    err = nvs_get_blob(handle, key, data, &required_size);
    nvs_close(handle);

    // Vérifie que la clé existe ET que la taille enregistrée correspond à la structure actuelle
    if (err == ESP_OK && required_size != size)
    {
        ESP_LOGE("NVS", "Failed to load key -(length mismatch) %s %d %d", key, required_size, size);
        return ESP_ERR_NVS_INVALID_LENGTH;
    }
    else if (err != ESP_OK)
    {
        ESP_LOGE("NVS", "Failed to load key %s [%x]", key, err);
        return err;
    }

    return err;
}

uint8_t get_battery_percentage(battery_type_t battery_type, uint32_t voltage_main)
{
  const batt_threshold_t *lut = (battery_type == BATTERY_3S) ? lut_3s : lut_4s;
  
  if (battery_type == BATTERY_UNKNOWN) return 0;

  for (int i = 0; i < 11; i++) {
    if (voltage_main >= lut[i].voltage_mv) {
      return lut[i].percent;
    }
  }
  return 0;
}

battery_type_t identify_battery_type(uint32_t voltage_main)
{
  // Simple heuristic based on voltage_main to determine battery type
  if (voltage_main > 14000)
  { // >14V is likely a 4S LiPo
    return BATTERY_4S;
  }
  else if (voltage_main > 10800)
  {
    return BATTERY_3S;
  }
  else
  {
    return BATTERY_UNKNOWN;
  }
}
